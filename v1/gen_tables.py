#!/usr/bin/env python3
"""Generate lookup tables (tables.inc, DASM syntax) for the RayWalls 2600 demo."""
import math, sys

COLS = int(sys.argv[1]) if len(sys.argv) > 1 else 40
OUT = sys.argv[2] if len(sys.argv) > 2 else "tables.inc"

HFOV = math.radians(66)          # horizontal field of view
ASPECT = 1.6                     # 2600 pixel is ~1.6x wider than tall
NLEV = 16
# scanlines per level, level 1 = next to the horizon (thin = finer detail far away)
LINES = [3, 3, 3, 3, 4, 4, 4, 5, 5, 5, 6, 6, 6, 7, 8, 8]
assert sum(LINES) == 80
MAXD = 10
SPEED = 0.16
# grey stone, lit at eye level, darker toward the top/bottom of near walls
WALL_COL = [0x0E, 0x0E, 0x0C, 0x0C, 0x0C, 0x0A, 0x0A, 0x0A,
            0x08, 0x08, 0x08, 0x06, 0x06, 0x06, 0x04, 0x04]

out = []
def tab(name, vals, per=16):
    out.append(f"{name}")
    for i in range(0, len(vals), per):
        out.append("        .byte " + ",".join(f"${v & 255:02X}" for v in vals[i:i+per]))

def A(i): return 2 * math.pi * i / 256

# --- page-aligned kernel tables (index 0 and 17 are sentinels) ---
tab("LINES", [0] + LINES + [0])
tab("COLT", [WALL_COL[0]] + WALL_COL + [WALL_COL[-1]])
kern = out[:]; out.clear()

# --- per-column tables ---
f = (COLS / 2) / math.tan(HFOV / 2)
coloff, ccos, cmask, carr = [], [], [], []
for c in range(COLS):
    camx = (c + 0.5 - COLS / 2)
    st = round(math.atan(camx / f) / (2 * math.pi / 256))
    coloff.append(st & 255)
    ccos.append(min(255, round(math.cos(A(st)) * 256)))
    # playfield pixel(s) for this column
    w = 40 // COLS
    p = c * w
    half, i = divmod(p, 20)
    if i < 4:   reg, bits = 0, [4 + i + k for k in range(w)]
    elif i < 12: reg, bits = 1, [7 - (i - 4) - k for k in range(w)]
    else:       reg, bits = 2, [(i - 12) + k for k in range(w)]
    m = 0
    for b in bits: m |= 1 << b
    cmask.append(m)
    carr.append((half * 3 + reg) * NLEV)
tab("COLOFF", coloff); tab("CCOS", ccos); tab("COLMASK", cmask); tab("COLARR", carr)

# --- height table: perp distance (4.4 fixed) -> number of lit levels ---
fv = f * (160 / COLS) * ASPECT   # vertical focal length in scanlines
cum = [0]
for l in LINES: cum.append(cum[-1] + l)
htab = []
for idx in range(160):
    perp = max(idx + 0.5, 0.5) / 16
    half = fv / 2 / perp
    h = 0
    for l in range(1, NLEV + 1):
        if cum[l] - LINES[l - 1] / 2 <= half: h = l
    htab.append(h)
tab("HTAB", htab)

# --- 1/|cos| (8.8), capped ---
ddl, ddh = [], []
for i in range(256):
    c = abs(math.cos(A(i)))
    v = 0x3FFF if c < 1 / 63.9 else min(0x3FFF, round(256 / c))
    ddl.append(v & 255); ddh.append(v >> 8)
tab("DDL", ddl); tab("DDH", ddh)

# --- movement (signed) ---
tab("MOVC", [round(SPEED * 256 * math.cos(A(i))) for i in range(256)])

# --- quarter squares ---
sq = [n * n // 4 for n in range(512)]
tab("SQL0", [v & 255 for v in sq[:256]]); tab("SQH0", [v >> 8 for v in sq[:256]])
tab("SQL1", [v & 255 for v in sq[256:]]); tab("SQH1", [v >> 8 for v in sq[256:]])

MAP = """\
################
#......#.......#
#.##...#..##...#
#.#....#...#...#
#.#..###...#...#
#..............#
####.##.####.###
#......#.......#
#.#.#..#..#....#
#......#..#.##.#
#.#.#.....#....#
#......####....#
###.####....#..#
#.......#...#..#
#...#.......#..#
################"""
rows = MAP.split("\n")
assert len(rows) == 16 and all(len(r) == 16 for r in rows)
tab("MAP", [1 if ch == '#' else 0 for r in rows for ch in r])

hdr = [f"; generated by gen_tables.py COLS={COLS}",
       f"COLS    = {COLS}", f"MAXD    = {MAXD}"]
open(OUT, "w").write("\n".join(out) + "\n")
open(OUT.replace("tables", "tables_k"), "w").write("\n".join(hdr + kern) + "\n")
print("wrote", OUT, "COLS", COLS)
